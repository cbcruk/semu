/** 기본 계정과목 ID입니다. 정렬 순서로 정하므로 환경이 달라도 같습니다. */
export function systemAccountTitleId(sortOrder: number): Id<'accountTitle'> {
  return `acc_${String(sortOrder).padStart(26, '0')}` as Id<'accountTitle'>
}

/** semu 기본 계정과목입니다. 모든 회사가 함께 보고, 이름을 바꾸거나 지울 수 없습니다. */
export const SYSTEM_ACCOUNT_TITLES: ReadonlyArray<AccountTitleRecord> = ROWS.map(
  ([sortOrder, parent, depth, code, name, description, appliesTo, plCategory, cashCategory]) => ({
    id: systemAccountTitleId(sortOrder),
    companyId: null,
    parentId: parent === null ? null : systemAccountTitleId(parent),
    depth,
    code,
    name,
    description,
    appliesTo,
    plCategory,
    cashCategory,
    origin: 'SYSTEM',
    sortOrder,
    version: 1,
  }),
)

/** 기본 계정과목 ID를 코드로 찾습니다. 시드와 테스트가 씁니다. */
export function systemAccountTitleIdOf(code: string): Id<'accountTitle'> {
  const found = SYSTEM_ACCOUNT_TITLES.find((row) => row.code === code)
  if (found === undefined) throw new Error(`Unknown system account title ${code}`)
  return found.id
}
